-- Database-level guardrails: application permissions alone must not make history mutable.
CREATE FUNCTION streamops.reject_audit_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit_logs are append-only';
END;
$$;
CREATE TRIGGER audit_logs_append_only
BEFORE UPDATE OR DELETE ON audit_logs
FOR EACH ROW EXECUTE FUNCTION streamops.reject_audit_mutation();

CREATE FUNCTION streamops.guard_financial_transaction_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status <> 'draft' OR NEW.status NOT IN ('draft','posted') THEN
    RAISE EXCEPTION 'posted financial transactions cannot be modified; use an approved adjustment entry';
  END IF;
  IF (to_jsonb(NEW) - 'status') <> (to_jsonb(OLD) - 'status') THEN
    RAISE EXCEPTION 'financial transaction details are immutable; use an approved adjustment entry';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER financial_transactions_guard_update
BEFORE UPDATE ON financial_transactions
FOR EACH ROW EXECUTE FUNCTION streamops.guard_financial_transaction_update();

CREATE FUNCTION streamops.reject_settlement_line_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  parent_status varchar(24);
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT status INTO parent_status FROM streamops.settlements
      WHERE id = NEW.settlement_id AND agency_id = NEW.agency_id;
    IF parent_status <> 'draft' THEN
      RAISE EXCEPTION 'settlement lines can only be added to a draft settlement';
    END IF;
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'settlement lines are immutable; correct with a new adjustment workflow';
END;
$$;
CREATE TRIGGER settlement_lines_immutable
BEFORE INSERT OR UPDATE OR DELETE ON settlement_lines
FOR EACH ROW EXECUTE FUNCTION streamops.reject_settlement_line_mutation();

CREATE FUNCTION streamops.guard_locked_settlement() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'settlements cannot be deleted';
  END IF;
  IF (to_jsonb(NEW) - ARRAY['status','approved_by','approved_at','locked_at']) <>
     (to_jsonb(OLD) - ARRAY['status','approved_by','approved_at','locked_at']) THEN
    RAISE EXCEPTION 'settlement figures and scope are immutable';
  END IF;
  IF OLD.status = 'draft' AND NEW.status = 'submitted' AND
     NEW.approved_by IS NOT DISTINCT FROM OLD.approved_by AND
     NEW.approved_at IS NOT DISTINCT FROM OLD.approved_at AND
     NEW.locked_at IS NOT DISTINCT FROM OLD.locked_at THEN
    RETURN NEW;
  END IF;
  IF OLD.status = 'submitted' AND NEW.status = 'locked' AND
     NEW.approved_by IS NOT NULL AND NEW.approved_at IS NOT NULL AND NEW.locked_at IS NOT NULL THEN
    RETURN NEW;
  END IF;
  RAISE EXCEPTION 'invalid settlement state transition';
END;
$$;
CREATE TRIGGER settlements_locked_immutable
BEFORE UPDATE OR DELETE ON settlements
FOR EACH ROW EXECUTE FUNCTION streamops.guard_locked_settlement();

CREATE FUNCTION streamops.guard_payout_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' OR OLD.status <> 'pending' OR NEW.status <> 'paid' OR
     (to_jsonb(NEW) - ARRAY['status','payment_reference','paid_at']) <>
     (to_jsonb(OLD) - ARRAY['status','payment_reference','paid_at']) OR
     NEW.payment_reference IS NULL OR NEW.paid_at IS NULL THEN
    RAISE EXCEPTION 'payout details are immutable; only a pending-to-paid transition is allowed';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER payouts_guard_update
BEFORE UPDATE OR DELETE ON payouts
FOR EACH ROW EXECUTE FUNCTION streamops.guard_payout_update();

