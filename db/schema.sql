CREATE TABLE live_schedules (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), streamer_id uuid NOT NULL,
  channel_id uuid, title varchar(180) NOT NULL, planned_start_at timestamptz NOT NULL,
  planned_end_at timestamptz NOT NULL, status varchar(24) NOT NULL DEFAULT 'proposed', created_by uuid NOT NULL,
  UNIQUE(agency_id,id),
  FOREIGN KEY(agency_id,streamer_id) REFERENCES streamers(agency_id,id),
  FOREIGN KEY(agency_id,channel_id) REFERENCES channels(agency_id,id),
  FOREIGN KEY(agency_id,created_by) REFERENCES asp_net_users(agency_id,id),
  CHECK(planned_end_at > planned_start_at)
);
CREATE INDEX live_schedules_calendar_idx ON live_schedules(agency_id,planned_start_at);
CREATE TABLE live_sessions (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), streamer_id uuid NOT NULL,
  schedule_id uuid, channel_id uuid, actual_start_at timestamptz, actual_end_at timestamptz,
