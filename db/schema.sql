CREATE UNIQUE INDEX user_name_index ON asp_net_users(normalized_user_name) WHERE normalized_user_name IS NOT NULL;
CREATE INDEX email_index ON asp_net_users(normalized_email);

CREATE TABLE asp_net_role_claims (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id uuid NOT NULL REFERENCES asp_net_roles(id) ON DELETE CASCADE,
  claim_type text, claim_value text
);
CREATE INDEX role_claim_role_id_index ON asp_net_role_claims(role_id);
CREATE TABLE asp_net_user_claims (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES asp_net_users(id) ON DELETE CASCADE,
  claim_type text, claim_value text
);
CREATE INDEX user_claim_user_id_index ON asp_net_user_claims(user_id);
CREATE TABLE asp_net_user_logins (
  login_provider varchar(128) NOT NULL, provider_key varchar(128) NOT NULL,
  provider_display_name text, user_id uuid NOT NULL REFERENCES asp_net_users(id) ON DELETE CASCADE,
  PRIMARY KEY(login_provider, provider_key)
);
CREATE INDEX user_login_user_id_index ON asp_net_user_logins(user_id);
CREATE TABLE asp_net_user_roles (
  user_id uuid NOT NULL REFERENCES asp_net_users(id) ON DELETE CASCADE,
  role_id uuid NOT NULL REFERENCES asp_net_roles(id) ON DELETE CASCADE,
  PRIMARY KEY(user_id, role_id)
);
CREATE INDEX user_role_role_id_index ON asp_net_user_roles(role_id);
CREATE TABLE asp_net_user_tokens (
  user_id uuid NOT NULL REFERENCES asp_net_users(id) ON DELETE CASCADE,
  login_provider varchar(128) NOT NULL, name varchar(128) NOT NULL, value text,
  PRIMARY KEY(user_id, login_provider, name)
);

-- Keep the first/owner role out of normal application-level invitation paths.
CREATE FUNCTION streamops.guard_admin_role_assignment() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  assigned_role text;
  table_owner text;
BEGIN
  SELECT normalized_name INTO assigned_role FROM streamops.asp_net_roles WHERE id = NEW.role_id;
  IF assigned_role = 'ADMIN' THEN
    SELECT pg_get_userbyid(relowner) INTO table_owner FROM pg_class
      WHERE oid = 'streamops.asp_net_user_roles'::regclass;
    IF current_user <> table_owner THEN
      RAISE EXCEPTION 'Admin role assignment is restricted to the database owner bootstrap process';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER asp_net_user_roles_guard_admin
BEFORE INSERT OR UPDATE ON asp_net_user_roles
FOR EACH ROW EXECUTE FUNCTION streamops.guard_admin_role_assignment();

CREATE TABLE teams (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), parent_team_id uuid,
  code varchar(32) NOT NULL, name varchar(120) NOT NULL, status varchar(24) NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(agency_id,id), UNIQUE(agency_id,code),
  FOREIGN KEY(agency_id,parent_team_id) REFERENCES teams(agency_id,id)
);
CREATE TABLE team_memberships (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), team_id uuid NOT NULL,
  user_id uuid NOT NULL, membership_role varchar(32) NOT NULL DEFAULT 'member',
  valid_from date NOT NULL, valid_to date,
  UNIQUE(team_id,user_id,valid_from),
  FOREIGN KEY(agency_id,team_id) REFERENCES teams(agency_id,id),
  FOREIGN KEY(agency_id,user_id) REFERENCES asp_net_users(agency_id,id),
  CHECK(valid_to IS NULL OR valid_to >= valid_from)
);
CREATE TABLE employee_profiles (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), user_id uuid NOT NULL,
  employee_code varchar(32) NOT NULL, job_title varchar(120) NOT NULL, manager_user_id uuid,
  hire_date date NOT NULL, end_date date, employment_status varchar(24) NOT NULL DEFAULT 'active',
  UNIQUE(agency_id,id), UNIQUE(agency_id,employee_code), UNIQUE(user_id),
  FOREIGN KEY(agency_id,user_id) REFERENCES asp_net_users(agency_id,id),
  FOREIGN KEY(agency_id,manager_user_id) REFERENCES asp_net_users(agency_id,id),
  CHECK(end_date IS NULL OR end_date >= hire_date)
);

CREATE TABLE streamers (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), code varchar(32) NOT NULL,
  stage_name varchar(120) NOT NULL, legal_name varchar(180), status varchar(24) NOT NULL DEFAULT 'lead',
  time_zone varchar(80) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh', account_user_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(agency_id,id), UNIQUE(agency_id,code),
  FOREIGN KEY(agency_id,account_user_id) REFERENCES asp_net_users(agency_id,id)
);
CREATE TABLE streamer_assignments (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), streamer_id uuid NOT NULL,
  team_id uuid, user_id uuid, assignment_role varchar(32) NOT NULL, valid_from date NOT NULL, valid_to date,
  FOREIGN KEY(agency_id,streamer_id) REFERENCES streamers(agency_id,id),
  FOREIGN KEY(agency_id,team_id) REFERENCES teams(agency_id,id),
  FOREIGN KEY(agency_id,user_id) REFERENCES asp_net_users(agency_id,id),
  CHECK(team_id IS NOT NULL OR user_id IS NOT NULL), CHECK(valid_to IS NULL OR valid_to >= valid_from)
);
CREATE INDEX streamer_assignments_scope_idx ON streamer_assignments(agency_id,user_id,valid_from,valid_to);
CREATE TABLE contracts (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), streamer_id uuid NOT NULL,
  contract_reference varchar(120) NOT NULL, valid_from date NOT NULL, valid_to date,
  signed_at timestamptz NOT NULL, streamer_rate numeric(7,4) NOT NULL, agency_rate numeric(7,4) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'active', created_by uuid NOT NULL,
  UNIQUE(agency_id,id), UNIQUE(agency_id,contract_reference),
  FOREIGN KEY(agency_id,streamer_id) REFERENCES streamers(agency_id,id),
  FOREIGN KEY(agency_id,created_by) REFERENCES asp_net_users(agency_id,id),
  CHECK(valid_to IS NULL OR valid_to >= valid_from),
  CHECK(streamer_rate >= 0 AND agency_rate >= 0 AND streamer_rate + agency_rate = 1)
);

CREATE TABLE channels (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), streamer_id uuid NOT NULL,
  platform_code varchar(40) NOT NULL, external_channel_id varchar(180) NOT NULL,
  handle varchar(180) NOT NULL, url text, status varchar(24) NOT NULL DEFAULT 'active',
  UNIQUE(agency_id,id), UNIQUE(agency_id,platform_code,external_channel_id),
  FOREIGN KEY(agency_id,streamer_id) REFERENCES streamers(agency_id,id)
