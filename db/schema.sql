-- StreamOps schema bootstrap for a new/empty dedicated database namespace.
-- This creates only the `streamops` schema; it does not alter public objects.
-- Review this file before applying it to any shared or production database.
BEGIN;
CREATE SCHEMA IF NOT EXISTS streamops;
SET LOCAL search_path TO streamops, public;

CREATE TABLE agencies (
  id uuid PRIMARY KEY,
  name varchar(180) NOT NULL,
  slug varchar(80) NOT NULL UNIQUE,
  time_zone varchar(80) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
  default_currency char(3) NOT NULL DEFAULT 'VND',
  created_at timestamptz NOT NULL DEFAULT now()
