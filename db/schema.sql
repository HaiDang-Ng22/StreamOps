CREATE TABLE session_metrics (
  id uuid PRIMARY KEY, agency_id uuid NOT NULL REFERENCES agencies(id), live_session_id uuid NOT NULL,
  metric_code varchar(60) NOT NULL, value numeric(20,4) NOT NULL CHECK(value >= 0),
  unit varchar(32) NOT NULL, source varchar(24) NOT NULL DEFAULT 'manual',
